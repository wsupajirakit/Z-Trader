/**
 * Request shapes shared by the machine API (`/gold/*`, x-api-key) and the dashboard (`/api/dashboard/*`).
 * The global ValidationPipe whitelists them, so both entry points accept exactly the same values.
 * The mode and instrument lists come from gold/domain, never from a copy.
 */
import { BadRequestException } from '@nestjs/common';
import { Transform, Type } from 'class-transformer';
import {
    ArrayMaxSize,
    IsArray,
    IsBoolean,
    IsIn,
    IsInt,
    IsOptional,
    IsString,
    Length,
    Matches,
    Max,
    MaxLength,
    Min,
} from 'class-validator';
import type { GoldMode } from '../data/gold-data.service';
import { INSTRUMENT_KEYS, MODE_KEYS } from '../domain/instruments';

export const VALID_MODES: readonly GoldMode[] = MODE_KEYS;
export const VALID_INSTRUMENTS: readonly string[] = INSTRUMENT_KEYS;

type TransformArg = { value: unknown };
const upper = ({ value }: TransformArg) => (typeof value === 'string' ? value.toUpperCase() : value);
/** lower-case a mode; null (sent explicitly) means "use the default", like an absent field */
const modeOr =
    (def: GoldMode) =>
    ({ value }: TransformArg) =>
        value === null ? def : typeof value === 'string' ? value.toLowerCase() : value;
const lower = ({ value }: TransformArg) => (typeof value === 'string' ? value.toLowerCase() : value);
const upperList = ({ value }: TransformArg) =>
    Array.isArray(value) ? value.map((v) => String(v).toUpperCase()) : value;
const lowerList = ({ value }: TransformArg) =>
    Array.isArray(value) ? value.map((v) => String(v).toLowerCase()) : value;

export class InstrumentDto {
    @Transform(upper)
    @IsIn(VALID_INSTRUMENTS)
    symbol!: string;
}

export class AutomateDto {
    @IsBoolean()
    enabled!: boolean;

    @IsOptional()
    @Transform(lowerList)
    @IsArray()
    @ArrayMaxSize(VALID_MODES.length)
    @IsIn(VALID_MODES, { each: true })
    modes?: GoldMode[];

    /** not sent = keep the current selection */
    @IsOptional()
    @Transform(upperList)
    @IsArray()
    @ArrayMaxSize(VALID_INSTRUMENTS.length)
    @IsIn(VALID_INSTRUMENTS, { each: true })
    instruments?: string[];
}

export class RunDto {
    @IsOptional()
    @Transform(modeOr('swing'))
    @IsIn(VALID_MODES)
    mode: GoldMode = 'swing';

    @IsOptional()
    @IsBoolean()
    force?: boolean;
}

/** machine `/gold/run` and `/gold/claude/analyze` may also switch the active instrument first */
export class MachineRunDto extends RunDto {
    @IsOptional()
    @Transform(upper)
    @IsIn(VALID_INSTRUMENTS)
    symbol?: string;
}

export class DecisionDto {
    @IsOptional()
    @Transform(modeOr('swing'))
    @IsIn(VALID_MODES)
    mode: GoldMode = 'swing';

    /** from the `awaiting-approval:<id>` outcome of an analysis */
    @IsString()
    @Length(1, 64)
    id!: string;
}

export class RejectDto extends DecisionDto {
    @IsOptional()
    @IsString()
    @MaxLength(300)
    reason?: string;
}

export class ActivityQuery {
    @IsOptional()
    @Type(() => Number)
    @IsInt()
    @Min(0)
    after = 0;
}

export class NewsQuery {
    @IsOptional()
    @Type(() => Number)
    @IsInt()
    @Min(1)
    @Max(50)
    limit = 20;
}

export class ArchiveListQuery {
    @IsOptional()
    @Transform(lower)
    @IsIn(VALID_MODES)
    mode?: GoldMode;

    @IsOptional()
    @Type(() => Number)
    @IsInt()
    @Min(1)
    @Max(200)
    limit = 20;
}

export class ArchiveFileParams {
    @Transform(lower)
    @IsIn(VALID_MODES)
    mode!: GoldMode;

    /** archive filenames are generated by the service: 20260804_091530_swing.json */
    @IsString()
    @Matches(/^[0-9]{8}_[0-9]{6}_[a-z]+\.json$/, { message: 'invalid archive file name' })
    file!: string;
}

export class ArchiveFileQuery {
    @IsOptional()
    @IsIn(['1', 'true', '0', 'false'])
    full?: string;
}

export class HistoryQuery {
    @IsOptional()
    @Type(() => Number)
    @IsInt()
    @Min(1)
    @Max(365)
    days = 30;
}

/**
 * The settings body is a partial map whose keys and ranges the service owns (setSettings validates
 * every field before applying any), so only its shape is checked here.
 */
export function settingsBody(body: unknown): Record<string, unknown> {
    if (!body || typeof body !== 'object' || Array.isArray(body))
        throw new BadRequestException('settings must be an object');
    return body as Record<string, unknown>;
}
